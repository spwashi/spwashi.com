/**
 * Generate and refresh `skill.spw` — the conventional surface beside each SKILL.md.
 *
 * A skill directory holds prose (SKILL.md), sometimes references/ and scripts/,
 * and sometimes a measurement surface over in .spw/skills. Nothing tied those
 * together, so a reader had to list the directory to find out what a skill was
 * made of, and the corpus could not cite into it at all.
 *
 * `skill.spw` is that surface. Named `skill.spw` rather than `index.spw` because
 * the tree already carries a dozen index.spw files and a thirteenth would make
 * every grep for one worse.
 *
 * The generated half is bounded by markers. Everything outside them is yours and
 * is preserved verbatim on refresh — a generator that clobbers hand-authored
 * facets would be worse than no generator, because the facets are the point.
 *
 *   ^"contents"  what is in the directory, with each file's role
 *   @refs        SKILL.md, references/, scripts/, and the measures surface
 *
 * Hand-authored blocks — operation, sense, probe, precipitate, refuse, extends —
 * live below the marker and survive every regeneration.
 *
 * Usage:
 *   node scripts/spw-skill-surface.mjs            # report what would change
 *   node scripts/spw-skill-surface.mjs --write
 *   node scripts/spw-skill-surface.mjs --write --only spw-craft-quality
 */

import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = path.join(ROOT, '.agents/skills');
const MEASURES = path.join(ROOT, '.spw/skills');

const BEGIN = '# <<< generated by scripts/spw-skill-surface.mjs — edits above this line are kept';
const END = '# >>> end generated';

/** Roles inferred from where a file sits, so the surface says what each part is for. */
const ROLE = {
  'SKILL.md': 'prose — the instructions a model reads',
  references: 'reference material the skill cites',
  scripts: 'executable helpers the skill invokes',
};

const exists = async (p) => { try { await stat(p); return true; } catch { return false; } };

function frontmatter(source) {
  const block = source.match(/^---\n([\s\S]*?)\n---/);
  if (!block) return {};
  const out = {};
  for (const line of block[1].split('\n')) {
    const m = line.match(/^(\w+):\s*(.*)$/);
    if (m) out[m[1]] = m[2].trim();
  }
  return out;
}

/** Escape for a Spw backtick literal. */
const lit = (s) => String(s).replace(/`/g, "'");

async function describe(id) {
  const dir = path.join(SKILLS, id);
  const entries = await readdir(dir, { withFileTypes: true });

  const skillMd = path.join(dir, 'SKILL.md');
  const meta = (await exists(skillMd)) ? frontmatter(await readFile(skillMd, 'utf8')) : {};

  const contents = [];
  const refs = [];

  if (await exists(skillMd)) {
    contents.push({ name: 'SKILL.md', role: ROLE['SKILL.md'] });
    refs.push(['prose', './SKILL.md']);
  }

  for (const entry of entries.filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const inner = await readdir(path.join(dir, entry.name));
    contents.push({
      name: `${entry.name}/`,
      role: ROLE[entry.name] || 'directory',
      holds: inner.sort(),
    });
    refs.push([entry.name, `./${entry.name}`]);
  }

  // The measurement surface is optional and lives in the corpus, not here.
  const measures = path.join(MEASURES, `${id.replace(/^spw-/, '').replace(/-audit$/, '')}.spw`);
  if (await exists(measures)) {
    refs.push(['measures', path.relative(dir, measures)]);
  }

  return { id, dir, meta, contents, refs };
}

function render({ id, meta, contents, refs }) {
  const anchor = `skill_${id.replace(/-/g, '_')}`;
  const lines = [];

  lines.push(BEGIN);
  lines.push(`#>${anchor}`);
  lines.push('#:skill #!agents');
  lines.push('#:layer #!pragmatics');
  lines.push('');
  if (meta.description) lines.push(`~#describes: "${lit(meta.description)}"`);
  lines.push('');
  for (const [name, target] of refs) lines.push(`@${name}: ~"${target}"`);
  lines.push('');
  lines.push('^"contents"{');
  for (const entry of contents) {
    if (entry.holds) {
      lines.push(`  "${entry.name}": .{ role = \`${lit(entry.role)}\`, holds = #[${entry.holds.map((h) => `\`${lit(h)}\``).join(', ')}][reg=set] }[reg=facet]`);
    } else {
      lines.push(`  "${entry.name}": .{ role = \`${lit(entry.role)}\` }[reg=facet]`);
    }
  }
  lines.push('}[reg=facet]');
  lines.push(END);

  return lines.join('\n');
}

/** Replace only the generated region; keep everything a human wrote around it. */
function splice(existing, generated, id) {
  if (!existing) {
    return `# ${id} — skill surface\n#\n# Generated contents below; hand-authored facets go underneath.\n# See .agents/skills/_shared/skill-surface.spw for the shape.\n\n${generated}\n`;
  }
  const begin = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  if (begin === -1 || end === -1) return `${existing.trimEnd()}\n\n${generated}\n`;
  return existing.slice(0, begin) + generated + existing.slice(end + END.length);
}

async function main() {
  const write = process.argv.includes('--write');
  const only = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1] : null;

  const dirs = (await readdir(SKILLS, { withFileTypes: true }))
    .filter((e) => e.isDirectory() && e.name !== '_shared')
    .map((e) => e.name)
    .filter((name) => !only || name === only)
    .sort();

  let changed = 0;
  for (const id of dirs) {
    const described = await describe(id);
    const target = path.join(described.dir, 'skill.spw');
    const before = (await exists(target)) ? await readFile(target, 'utf8') : '';
    const after = splice(before, render(described), id);

    if (before === after) continue;
    changed += 1;
    const verb = before ? 'refresh' : 'create';
    console.log(`  ${verb.padEnd(8)} ${path.relative(ROOT, target)}  (${described.contents.length} entries, ${described.refs.length} refs)`);
    if (write) await writeFile(target, after, 'utf8');
  }

  console.log(`\n${dirs.length} skills scanned, ${changed} ${write ? 'written' : 'would change'}`);
  if (!write && changed) console.log('re-run with --write to apply');
}

main().catch((error) => {
  console.error('[spw-skill-surface]', error);
  process.exitCode = 1;
});
