/**
 * image-provenance-records.mjs — what each picture's sidecar says about how it was made.
 *
 * The runtime's path rules cover the folders whose contents are all one kind:
 * /public/images/renders/ is generated, /public/images/assets/folios/ is an
 * original scan. Everything else is read from its .spw sidecar, never guessed:
 * a generator or model field names the tool; a source kept under renders/, or a
 * source file in a generator's download naming (a uuid, --profile), marks it
 * generated without naming the tool. A sidecar covers the files its stem names
 * (garden-bed-atlas → garden-bed-atlas-display.webp) and any it lists in
 * files: #[...]. Pictures with no such record stay unmarked.
 *
 * scripts/image-provenance-index.mjs writes the result for the browser;
 * public/js/runtime/expression/image-provenance.js reads it.
 */
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

export const PROVENANCE_MODULE = 'public/js/generated/image-provenance.js';

const IMAGE_ROOT = 'public/images';
const PATH_RULED = Object.freeze(['public/images/renders', 'public/images/assets/folios']);
const UUID_RE = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/;
const TOOL_RE = /\b(?:generator|model)\s*[:=]\s*"([^"]+)"/;
const SOURCE_RE = /\bsource(?:_masters?|_render|_file)?\s*[:=]\s*(?:~?"([^"]+)"|#\[([\s\S]*?)\])/g;
const FILES_RE = /\bfiles\s*:\s*#\[([\s\S]*?)\]/;

/** { kind, tool } from one sidecar's text, or null when it records nothing. */
export function readProvenance(text = '') {
  const tool = TOOL_RE.exec(text)?.[1];
  if (tool) return { kind: 'generated', tool };
  if (/\bmidjourney_prompt\s*:/.test(text)) return { kind: 'generated', tool: 'Midjourney' };
  for (const match of text.matchAll(SOURCE_RE)) {
    const values = match[1] ? [match[1]] : [...match[2].matchAll(/"([^"]+)"/g)].map((value) => value[1]);
    if (values.some((value) => value.includes('renders/') || UUID_RE.test(value) || value.includes('--profile'))) {
      return { kind: 'generated', tool: null };
    }
  }
  return null;
}

function sidecarPaths(dir) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!PATH_RULED.includes(full)) found.push(...sidecarPaths(full));
    } else if (entry.name.endsWith('.spw')) {
      found.push(full);
    }
  }
  return found;
}

/**
 * Every recorded stem outside the path-ruled folders, sorted. An unrecorded
 * sidecar is listed with kind null only where a recorded stem is its prefix,
 * so the longest match can stop at it instead of borrowing the shorter record.
 */
export function collectProvenanceRecords(root = process.cwd()) {
  const records = [];
  const unrecorded = [];
  for (const file of sidecarPaths(IMAGE_ROOT)) {
    const text = readFileSync(path.join(root, file), 'utf8');
    const dir = `/${path.posix.dirname(file)}`;
    const stems = [path.posix.basename(file, '.spw')];
    const listed = FILES_RE.exec(text)?.[1];
    if (listed) stems.push(...[...listed.matchAll(/"([^"]+)"/g)].map((value) => value[1]));
    const provenance = readProvenance(text);
    for (const stem of stems) {
      const entry = { stem: `${dir}/${stem}`, kind: provenance?.kind ?? null, tool: provenance?.tool ?? null };
      (provenance ? records : unrecorded).push(entry);
    }
  }
  const shadows = unrecorded.filter(({ stem }) => records.some((record) => stem.startsWith(`${record.stem}-`)));
  return [...records, ...shadows].sort((a, b) => a.stem.localeCompare(b.stem));
}

export function renderProvenanceModule(records) {
  const rows = records.map((record) => `  Object.freeze(${JSON.stringify(record)}),`).join('\n');
  return `/**
 * GENERATED by scripts/image-provenance-index.mjs — do not edit.
 *
 * How each picture outside the path-ruled folders was made, as its .spw
 * sidecar records it (scripts/lib/image-provenance-records.mjs). A stem covers
 * <stem>.<ext> and <stem>-<tier>.<ext>; the longest matching stem wins, and a
 * null kind means the sidecar records nothing, so the picture stays unmarked.
 * Read by public/js/runtime/expression/image-provenance.js.
 */

export const IMAGE_PROVENANCE_RECORDS = Object.freeze([
${rows}
]);
`;
}
