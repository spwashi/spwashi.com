/**
 * Emit the legibility lens from what the modules already declare.
 *
 * Every catalog entry lists the attributes it writes, tagged with a channel:
 *
 *   structural   183   layout and meaning — the page is wrong without it
 *   flourish      64   decoration — the page is complete without it
 *   inspect       48   an inspection surface, not content
 *   residue       29   what a visit leaves behind and keeps
 *   measure       17   a measurement someone can check
 *   diagnostic     8   for debugging the runtime itself
 *
 * 349 declarations over 328 distinct attributes, and no stylesheet has ever
 * read the channel. Meanwhile 167 of 375 attributes in the markup are styled by
 * nothing at all. The channel is the missing join: it says which slice of the
 * data is worth making readable, which is a question no single attribute can
 * answer about itself.
 *
 * So the lens is a theme over *relevance* rather than over colour. Setting
 * `data-spw-legible="residue"` on the root makes the attributes that survive a
 * visit readable and leaves everything else quiet; `measure` surfaces the
 * checkable claims; `structural` shows what is load-bearing. One slice at a
 * time, because a page showing all six is not a lens, it is a debug overlay.
 *
 * Generated rather than authored: the channels live in the catalogs, and a
 * hand-maintained copy would drift the first time a module changed what it
 * writes.
 *
 * Usage:
 *   node scripts/build-legibility-lens.mjs           # report
 *   node scripts/build-legibility-lens.mjs --write   # emit the stylesheet
 */

import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG_DIR = path.join(ROOT, 'public/js/runtime');
const OUT = path.join(ROOT, 'public/css/systems/legibility-lens.css');

/** Channels ordered by how load-bearing they are. Order drives the cascade. */
const CHANNEL_ORDER = ['structural', 'measure', 'residue', 'inspect', 'flourish', 'diagnostic'];

const CHANNEL_NOTE = {
  structural: 'layout and meaning — the page is wrong without these',
  measure: 'a measurement someone can check',
  residue: 'what a visit leaves behind and keeps',
  inspect: 'an inspection surface, not content',
  flourish: 'decoration — the page is complete without these',
  diagnostic: 'for debugging the runtime itself',
};

async function collectChannels() {
  const files = (await readdir(CATALOG_DIR))
    .filter((name) => name.startsWith('module-catalog-') && name.endsWith('.js'));

  const byChannel = new Map();
  for (const file of files) {
    const source = await readFile(path.join(CATALOG_DIR, file), 'utf8');
    for (const match of source.matchAll(/'([a-z-]+):(data-spw-[a-z-]+)'/g)) {
      const [, channel, attribute] = match;
      if (!byChannel.has(channel)) byChannel.set(channel, new Set());
      byChannel.get(channel).add(attribute);
    }
  }
  return byChannel;
}

function render(byChannel) {
  const channels = CHANNEL_ORDER.filter((c) => byChannel.has(c));
  const total = channels.reduce((sum, c) => sum + byChannel.get(c).size, 0);

  const lines = [];
  lines.push('/* ==========================================================================');
  lines.push('   legibility-lens.css');
  lines.push('   --------------------------------------------------------------------------');
  lines.push('   GENERATED by scripts/build-legibility-lens.mjs — do not edit by hand.');
  lines.push('');
  lines.push('   A theme over relevance rather than over colour. Each module declares which');
  lines.push('   channel every attribute it writes belongs to; this turns those declarations');
  lines.push('   into a lens, so a reader can make one slice of the data readable and leave');
  lines.push('   the rest quiet.');
  lines.push('');
  lines.push(`   ${total} attributes over ${channels.length} channels.`);
  lines.push('');
  lines.push('   Set data-spw-legible on the root to choose a slice:');
  for (const c of channels) {
    lines.push(`     ${c.padEnd(11)} ${String(byChannel.get(c).size).padStart(3)}  ${CHANNEL_NOTE[c] || ''}`);
  }
  lines.push('');
  lines.push('   Nothing is legible by default. A page that reveals all six channels at once');
  lines.push('   is a debug overlay, not a lens, and the point of a lens is that it leaves');
  lines.push('   most of the page alone.');
  lines.push('   ========================================================================== */');
  lines.push('');
  lines.push(':root {');
  lines.push('  --spw-lens-ink: var(--spw-charge-field-color, var(--active-op-color, #008080));');
  lines.push('  --spw-lens-ground: color-mix(in oklab, var(--spw-lens-ink) 8%, transparent);');
  lines.push('}');
  lines.push('');

  for (const channel of channels) {
    const attributes = [...byChannel.get(channel)].sort();
    lines.push(`/* ---- ${channel} — ${CHANNEL_NOTE[channel] || ''} (${attributes.length}) ---- */`);
    lines.push('');

    const selector = attributes
      .map((attr) => `[data-spw-legible="${channel}"] :where([${attr}])`)
      .join(',\n');
    lines.push(`${selector} {`);
    lines.push('  outline: 1px dashed color-mix(in oklab, var(--spw-lens-ink) 38%, transparent);');
    lines.push('  outline-offset: 2px;');
    lines.push('  background-color: var(--spw-lens-ground);');
    lines.push('}');
    lines.push('');
  }

  // Motion and capture behave the same as every other reveal on the site.
  lines.push('@media (prefers-reduced-motion: reduce) {');
  lines.push('  [data-spw-legible] :where([class]) { transition: none; }');
  lines.push('}');
  lines.push('');
  lines.push('/* A lens is a reading aid, never a printed artifact. */');
  lines.push('@media print {');
  lines.push('  [data-spw-legible] :where([class]) { outline: none; background-color: transparent; }');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

async function main() {
  const byChannel = await collectChannels();
  const channels = CHANNEL_ORDER.filter((c) => byChannel.has(c));
  const unknown = [...byChannel.keys()].filter((c) => !CHANNEL_ORDER.includes(c));

  const total = channels.reduce((sum, c) => sum + byChannel.get(c).size, 0);
  console.log(`${total} attributes over ${channels.length} channels`);
  for (const c of channels) {
    console.log(`  ${c.padEnd(12)} ${String(byChannel.get(c).size).padStart(4)}  ${CHANNEL_NOTE[c] || ''}`);
  }
  if (unknown.length) {
    console.log(`\nchannels not in CHANNEL_ORDER (add them, or fix the declaration): ${unknown.join(', ')}`);
  }

  if (!process.argv.includes('--write')) {
    console.log('\nre-run with --write to emit public/css/systems/legibility-lens.css');
    return;
  }

  await writeFile(OUT, render(byChannel), 'utf8');
  console.log(`\nwrote ${path.relative(ROOT, OUT)}`);
}

main().catch((error) => {
  console.error('[legibility-lens]', error);
  process.exitCode = 1;
});
