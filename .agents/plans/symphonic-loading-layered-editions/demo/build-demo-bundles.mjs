/**
 * Demo-only bundle builder for the symphonic-loading pilot review.
 * Emits movement-grouped CSS bundles under design/experiments/load-symphony/css/.
 * NOT part of the production pipeline (scripts/css-bundle.mjs owns that);
 * invalidatable at will — regenerate with: node .agents/plans/symphonic-loading-layered-editions/demo/build-demo-bundles.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const OUT = resolve(ROOT, 'design/experiments/load-symphony/css');
const LAYER_ORDER = '@layer reset, tokens, shell, typography, grammar, components, systems, routes, handles, effects, ornament;\n';

const importRe = /@import url\(['"]?(\/public\/css\/[^'")]+)['"]?\)(?:\s+layer\((\w+)\))?/g;

function readImports(manifestPath) {
  const css = readFileSync(resolve(ROOT, manifestPath.slice(1)), 'utf8');
  const entries = [];
  for (const m of css.matchAll(importRe)) entries.push({ href: m[1], layer: m[2] ?? null });
  return entries;
}

// style-core.css owns the shared kernel; style.css adds shared extras + route surfaces.
const core = readImports('/public/css/style-core.css');
const full = readImports('/public/css/style.css').filter((e) => !e.href.endsWith('style-core.css'));

const MOVEMENTS = {
  'movement-1-2-reading': ['reset', 'tokens', 'shell', 'typography', 'grammar', 'components', 'systems'],
  'movement-3-instruments': ['handles'],
  'movement-4-atmosphere': ['effects', 'ornament'],
};
const ROUTE_LAYER = 'routes';

function bundleFor(entries, layers, { includeRoutes = false, routeFilter = null } = {}) {
  const parts = [LAYER_ORDER];
  for (const e of entries) {
    const isRoute = e.layer === ROUTE_LAYER;
    if (isRoute && !includeRoutes) continue;
    if (isRoute && routeFilter && !routeFilter(e.href)) continue;
    if (!isRoute && !layers.includes(e.layer)) continue;
    const filePath = resolve(ROOT, e.href.slice(1));
    let css;
    try { css = readFileSync(filePath, 'utf8'); } catch { console.warn(`skip missing ${e.href}`); continue; }
    // strip nested external imports (fonts move to <link> in the demo head)
    css = css.replace(/@import url\("https:[^\n]+\n/g, '');
    parts.push(`/* ${e.href} */\n@layer ${e.layer} {\n${css}\n}\n`);
  }
  return parts.join('\n');
}

mkdirSync(OUT, { recursive: true });
const all = [...core, ...full];
const topicsOnly = (href) => href.includes('/routes/surfaces/topics');

const outputs = {
  'movement-1-2-reading.css': bundleFor(all, MOVEMENTS['movement-1-2-reading']),
  'movement-2b-route-topics.css': bundleFor(all, [], { includeRoutes: true, routeFilter: topicsOnly }),
  'movement-3-instruments.css': bundleFor(all, MOVEMENTS['movement-3-instruments']),
  'movement-4-atmosphere.css': bundleFor(all, MOVEMENTS['movement-4-atmosphere']),
};

for (const [name, css] of Object.entries(outputs)) {
  writeFileSync(resolve(OUT, name), `/* demo bundle — generated by build-demo-bundles.mjs; do not hand-edit */\n${css}`);
  console.log(`${name}: ${(css.length / 1024).toFixed(0)}K`);
}

// movement map report for the proposal doc
for (const [movement, layers] of Object.entries(MOVEMENTS)) {
  const files = all.filter((e) => layers.includes(e.layer));
  const bytes = files.reduce((s, e) => { try { return s + readFileSync(resolve(ROOT, e.href.slice(1))).length; } catch { return s; } }, 0);
  console.log(`${movement}: ${files.length} files, ${(bytes / 1024).toFixed(0)}K source`);
}
