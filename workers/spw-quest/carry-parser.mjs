// Carry the site's browser parser bundle into the spw.quest worker as text.
//   node workers/spw-quest/carry-parser.mjs          write src/parser-text.js
//   node workers/spw-quest/carry-parser.mjs --check  exit 1 when it differs from the bundle
// Run it after `npm run build:spw-parser`. The worker serves the text at /parser.js
// and imports the bundle itself to read lines on the server; the route test holds
// the two to the same bytes.
import { readFile, writeFile } from "node:fs/promises";

const BUNDLE = new URL("../../public/js/semantic/spw-workbench-parser.js", import.meta.url);
const OUTPUT = new URL("./src/parser-text.js", import.meta.url);

export function carry(bundle) {
  return `// Generated by workers/spw-quest/carry-parser.mjs from public/js/semantic/spw-workbench-parser.js. Do not edit.
// spw.quest serves this text at /parser.js, so the page reads lines without reaching spwashi.com.
export const PARSER_JS = ${JSON.stringify(bundle)};
`;
}

const expected = carry(await readFile(BUNDLE, "utf8"));
if (process.argv.includes("--check")) {
  const current = await readFile(OUTPUT, "utf8").catch(() => "");
  if (current !== expected) {
    console.error("[carry-parser] src/parser-text.js differs from the site bundle; run node workers/spw-quest/carry-parser.mjs");
    process.exit(1);
  }
  console.log("[carry-parser] src/parser-text.js matches the site bundle");
} else {
  await writeFile(OUTPUT, expected);
  console.log(`[carry-parser] wrote src/parser-text.js (${(expected.length / 1024).toFixed(1)} KiB)`);
}
