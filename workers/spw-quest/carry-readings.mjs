// Carry the guide's constant readings into the worker as data, so neither an
// isolate's start nor a request parses them.
//   node workers/spw-quest/carry-readings.mjs          write src/readings-data.js
//   node workers/spw-quest/carry-readings.mjs --check  exit 1 when it differs
// Two readings: the files each example's paths name (src/file-reader.js
// linksOf), which let the guide's reading open the file a path points to and
// list the files that point back; and which /learn panels use each mark and
// each brace pair, the edges back from a card on the guide to its panels.
// Run it after src/examples.js, src/steps.js, the readers or the parser change.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EXAMPLES } from "./src/examples.js";
import { linksOf } from "./src/file-reader.js";
import { readLine } from "./src/reader.js";
import { STEPS } from "./src/steps.js";

const OUTPUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "src/readings-data.js");

/** Each example's paths, by its id. */
const shelfLinks = () => EXAMPLES.map(({ id, script }) => [id, linksOf(script)]);

/** Which panels' lines use each operator and each brace pair, as the panels' indexes in order. */
function panelEdges() {
  const ops = new Map();
  const braces = new Map();
  const add = (map, key, index) => (map.get(key) || map.set(key, new Set()).get(key)).add(index);
  STEPS.forEach((step, index) => {
    for (const line of [step.try, ...(step.then || [])]) {
      const reading = readLine(step.id, line);
      for (const op of reading.operators) if (op.name) add(ops, op.name, index);
      for (const c of reading.containers) add(braces, c.name, index);
    }
  });
  const table = (map) => [...map].map(([key, set]) => [key, [...set]]);
  return { ops: table(ops), braces: table(braces) };
}

/** A table as an object literal, one key a line. */
const rows = (entries) => `{\n${entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(",\n")}\n}`;

export function carry() {
  const edges = panelEdges();
  return `// Generated by workers/spw-quest/carry-readings.mjs from src/examples.js and src/steps.js. Do not edit.

/** Each example's paths by its id: the file each names and the line it lands on. */
export const SHELF_LINKS = Object.freeze(${rows(shelfLinks())});

/** The /learn panels (indexes into STEPS) whose lines use each operator and each brace pair. */
export const PANEL_EDGES = Object.freeze({
  ops: ${rows(edges.ops).replace(/\n/g, "\n  ")},
  braces: ${rows(edges.braces).replace(/\n/g, "\n  ")},
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = carry();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== expected) {
      console.error("[carry-readings] src/readings-data.js differs from a fresh reading; run node workers/spw-quest/carry-readings.mjs");
      process.exit(1);
    }
    console.log("[carry-readings] src/readings-data.js matches the examples and the panels");
  } else {
    await writeFile(OUTPUT, expected);
    console.log(`[carry-readings] wrote src/readings-data.js (${(expected.length / 1024).toFixed(1)} KiB)`);
  }
}
